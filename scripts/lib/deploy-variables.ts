/** Every variable of both apps' deployments, the backend's first. */
export function deployVariables(): DeployVariable[] {
  const secrets = (app: AppName) => [
    ...secretsOf(app).map(({ variable }) => [variable, SECRET_NOTE] as const),
    [FINGERPRINTS_VARIABLE, "the secrets' fingerprints, which doctor compares (D134)"] as const,
  ];
  const integrations = (app: AppName) =>
    integrationKeys(app).map((name) => [name, integrationNote(name)] as const);
  return [
    ...rows("backend", "config", BACKEND_CONFIG),
    ...rows("backend", "by-hand", BACKEND_BY_HAND),
    ...rows("backend", "secret", secrets("backend")),
    ...rows("backend", "integration", integrations("backend")),
    ...rows("backend", "seed", BACKEND_SEED),
    ...rows("storefront", "config", STOREFRONT_CONFIG),
    ...rows("storefront", "by-hand", STOREFRONT_BY_HAND),
    ...rows("storefront", "secret", secrets("storefront")),
    ...rows("storefront", "integration", [...STOREFRONT_COPIED, ...integrations("storefront")]),
    ...rows("storefront", "seed", STOREFRONT_SEED),
  ];
}

const SOURCE_TITLE: Record<VariableSource, string> = {
  secret: "Secrets (`pnpm staging:secrets`; sealed on Railway, sensitive on Vercel)",
  integration: "Keys and addresses `pnpm staging:secrets` copies",
  config: "Set by the platform config (`.railway/railway.ts`, or Vercel itself)",
  "by-hand": "Set once by hand (DEPLOY.md, G11)",
  seed: "The first deployment only (D148, 5)",
};

const APP_TITLE: Record<AppName, string> = {
  backend: "Medusa on Railway (`medusa` and `medusa-worker`)",
  storefront: "The storefront on Vercel",
};

/** `pnpm bootstrap --deployment`'s text: the names by app and source, and the seed's order. */
export function formatDeploymentPlan(variables = deployVariables()): string {
  const lines = [
    "bootstrap --deployment: a deployment's variables, by name only. Nothing is written here: the",
    "platforms hold the values (DEPLOY.md), and the seed runs there, not on this machine.",
  ];
  for (const app of ["backend", "storefront"] as const) {
    lines.push("", APP_TITLE[app]);
    for (const source of ["secret", "integration", "config", "by-hand", "seed"] as const) {
      const group = variables.filter((each) => each.app === app && each.source === source);
      if (group.length === 0) continue;
      lines.push(`  ${SOURCE_TITLE[source]}`);
      const width = Math.max(...group.map((each) => each.name.length));
      for (const each of group) lines.push(`    ${each.name.padEnd(width)}  ${each.note}`);
    }
  }
  lines.push(
    "",
    'The first deployment (DEPLOY.md, "The first deployment"):',
    "  1. `pnpm staging:secrets`, then the plain and seed variables above;",
    "  2. Railway: `railway config apply`; the server's predeploy migrates, checks (`doctor",
    "     --app=backend --strict --online`) and, with SEED_ON_DEPLOY=medusa, runs the Medusa half;",
    "  3. Vercel: the Production build checks (`doctor --app=storefront --strict --online`),",
    "     migrates Payload and, with SEED_ON_BUILD=payload, runs the Payload half;",
    "  4. the two e-mails (Payload's reset link, Medusa Admin's invite) go to SEED_ADMIN_EMAIL;",
    "     then remove SEED_ON_BUILD and SEED_ON_DEPLOY, and the next deployments seed nothing.",
  );
  return lines.join("\n");
}

/** Why plain `pnpm bootstrap` must not run here, or `undefined`: it writes `.env` files. */
export function deploymentRefusal(env: Readonly<Record<string, string | undefined>>) {
  const named = ["DEPLOY_ENV", "VERCEL_ENV"].filter((key) => (env[key] ?? "").trim() !== "");
  if (named.length === 0) return undefined;
  return `${named.join(" and ")} ${named.length === 1 ? "is" : "are"} set, so this is a deployment: \`pnpm bootstrap\` writes .env files and development credentials, which a deployment never has. Run \`pnpm bootstrap --deployment\` for the names a deployment needs.`;
}
