// Every variable a deployment of the two apps reads (M7 D132 to D136, D148; T114), by name, with
// where its value comes from. `pnpm bootstrap --deployment` prints it, `pnpm staging:secrets` writes
// the rows it owns, and DEPLOY.md's table is this one. Names only: nothing here holds or reads a
// value. Its test holds it to `.railway/railway.ts`, the secrets table and the integrations' keys.
import { getIntegrationStatus, type AppName } from "@shopblok/integrations";
import { FINGERPRINTS_VARIABLE, secretsOf } from "./deploy-secrets.ts";

/**
 * Where a value comes from:
 *
 * - `secret`: generated by `pnpm staging:secrets` and stored sealed (Railway) or sensitive (Vercel),
 *   with its fingerprint in `SHOPBLOK_SECRET_FINGERPRINTS` (D134);
 * - `integration`: an integration's test key, copied by `pnpm staging:secrets` from the session
 *   (D115; R2's from the `STAGING_S3_*` names), or Stripe's webhook secret, which it gets from
 *   Stripe; never typed into a dashboard;
 * - `config`: set by `.railway/railway.ts` (a value, or a reference Railway fills in) or by Vercel
 *   itself;
 * - `by-hand`: set once in G11 (DEPLOY.md), a plain value and no secret;
 * - `seed`: the first deployment only, removed afterwards (D148, 5).
 */
export type VariableSource = "secret" | "integration" | "config" | "by-hand" | "seed";

export type DeployVariable = {
  name: string;
  app: AppName;
  source: VariableSource;
  /** One line on what it holds or who sets it. */
  note: string;
};

const SECRET_NOTE = "generated, sealed, fingerprinted (`pnpm staging:secrets`)";

/** The integrations' keys, as `pnpm staging:secrets` copies them, per app (required keys only). */
function integrationKeys(app: AppName): string[] {
  const statuses = getIntegrationStatus({ backend: {}, storefront: {} }, { app });
  return [
    ...new Set(
      statuses
        .filter((status) => status.kind === "third-party")
        .flatMap((status) => status.parts.flatMap((part) => part.missing)),
    ),
  ];
}

const integrationNote = (name: string): string =>
  name === "STRIPE_WEBHOOK_SECRET"
    ? "the webhook's signing secret, from Stripe (`pnpm staging:secrets` finds the webhook by URL)"
    : name.startsWith("S3_")
      ? "staging's R2 buckets, from the session's `STAGING_S3_*`"
      : "the integration's test key, from the session";

const rows = (
  app: AppName,
  source: VariableSource,
  entries: readonly (readonly [name: string, note: string])[],
): DeployVariable[] => entries.map(([name, note]) => ({ name, app, source, note }));

