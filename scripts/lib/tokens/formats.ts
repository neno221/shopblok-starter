type Json =
  string | number | boolean | undefined | Json[] | { [key: string]: Json };

/** Prettier's default, which the repo's `prettier --check` uses (no config is set). */
const PRINT_WIDTH = 80;

/** Objects and arrays always one entry per line, so that Prettier leaves them as they are. */
function serialize(value: Json, indent = 0): string {
  const pad = "  ".repeat(indent + 1);
  const end = "  ".repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((v) => `${pad}${serialize(v, indent + 1)},`).join("\n")}\n${end}]`;
  }
  if (typeof value === "object" && value !== null) {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (entries.length === 0) return "{}";
    const lines = entries.map(([k, v]) => {
      const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
      const one = `${pad}${key}: ${serialize(v, indent + 1)},`;
      // Prettier moves a string that doesn't fit its line under the key.
      return typeof v === "string" && one.length > PRINT_WIDTH
        ? `${pad}${key}:\n${pad}  ${JSON.stringify(v)},`
        : one;
    });
    return `{\n${lines.join("\n")}\n${end}}`;
  }
  return JSON.stringify(value);
}

export function renderTs(model: Model): string {
  const colors = model.colors.map((c) => ({
    name: c.name,
    variable: `--${c.name}`,
    value: c.value,
    source: c.source,
    group: c.group,
    kit: c.override
      ? {
          source: c.override.kit,
          value: c.override.kitValue,
          reason: c.override.reason,
        }
      : undefined,
  }));
  const pairs = model.pairs.map((p) => ({
    id: p.id,
    kind: p.kind,
    minimum: p.minimum,
    alpha: p.alpha,
    foreground: { name: p.foreground.name, value: p.foreground.hex },
    background: { name: p.background.name, value: p.background.hex },
    over: p.over ? { name: p.over.name, value: p.over.hex } : undefined,
    ratio: Number(formatRatio(p.ratio, p.minimum)),
    kit: p.kit
      ? {
          ratio: Number(formatRatio(p.kit.ratio, p.minimum)),
          passes: p.kit.passes,
        }
      : undefined,
  }));
  const data = {
    colors,
    contrast: pairs,
    radius: { base: model.radius.base, steps: model.radius.steps },
    text: model.text,
    shadows: model.shadows.map((s) => ({
      name: s.name,
      value: shadowValue(s.layers),
    })),
    breakpoints: model.breakpoints,
    viewports: model.viewports,
    zIndex: model.zIndex,
  };
  const body = Object.entries(data)
    .map(
      ([name, value]) =>
        `export const ${name} = ${serialize(value as Json)} as const;`,
    )
    .join("\n\n");
  return `${GENERATED_BY.map((text) => `// ${text}`).join("\n")}\n// For the design-system pages (T26): what tokens.css holds, where each value comes from, the\n// kit's value where this repo overrides it, and the ratio of every contrast pair. Not a runtime\n// dependency of any component.\n\n${body}\n`;
}

// ---------------------------------------------------------------------------------------------
// Style Dictionary hooks

export const formats = {
  "shopblok/css": ({ dictionary }: { dictionary: Dictionary }) =>
    renderCss(buildModel(dictionary)),
  "shopblok/ts": ({ dictionary }: { dictionary: Dictionary }) =>
    renderTs(buildModel(dictionary)),
};
