// The two Style Dictionary formats (M1 plan, T19 step 5; D26, D27): `shopblok/css` writes
// `tokens.css`, `:root` for the semantic values and `@theme inline` to map them to Tailwind's
// names; `shopblok/ts` writes `tokens.ts`, the same facts as data for the design-system pages.
// Both render the model `model.ts` builds from the resolved tokens, so a check that fails stops
// either one, and neither writes a date or anything else that changes between runs.
import { formatRatio } from "./contrast.ts";
import {
  buildModel,
  type ColorEntry,
  type Model,
  type ShadowLayer,
} from "./model.ts";
import type { Dictionary } from "style-dictionary/types";

/** The header of both files, one line per entry. */
export const GENERATED_BY = [
  "Generated by Style Dictionary through scripts/figma-tokens.ts, from",
  "packages/ui/tokens/figma.tokens.json and shopblok.tokens.json.",
  "Do not edit: run `pnpm tokens`.",
] as const;

/** The system stack after `next/font`'s variable (D28). The same words T20 wrote in globals.css. */
const FONT_FALLBACK = [
  "system-ui",
  "sans-serif",
  '"Apple Color Emoji"',
  '"Segoe UI Emoji"',
  '"Segoe UI Symbol"',
  '"Noto Color Emoji"',
];

/** px as rem on a 16 px root, without trailing zeros: 12 is 0.75rem, 10 is 0.625rem. */
export function rem(px: number): string {
  if (px === 0) return "0";
  return `${Number((px / 16).toFixed(6))}rem`;
}

const px = (value: number): string => (value === 0 ? "0" : `${value}px`);

export function shadowValue(layers: readonly ShadowLayer[]): string {
  return layers
    .map(
      (l) => `${px(l.x)} ${px(l.y)} ${px(l.blur)} ${px(l.spread)} ${l.color}`,
    )
    .join(", ");
}

function colorValue(color: ColorEntry): string {
  return color.primitive ? `var(--${color.primitive})` : color.value;
}

export function renderCss(model: Model): string {
  const out: string[] = [];
  const line = (text = "") => out.push(text);
  line("/*");
  for (const text of GENERATED_BY) line(` * ${text}`);
  line(" */");
  line();
  line(":root {");
  line(
    "  /* Primitives that a semantic token below is written as var() of. */",
  );
  for (const p of model.primitives) line(`  --${p.name}: ${p.value};`);
  line();
  line("  /* shadcn's contract (SPEC §9.2). Light only. */");
  for (const c of model.colors.filter((c) => c.group === "contract")) {
    const note = c.override ? ` /* the kit: ${c.override.kitValue} */` : "";
    line(`  --${c.name}: ${colorValue(c)};${note}`);
  }
  line(`  --radius: ${rem(model.radius.base)};`);
  line();
  line("  /* Commerce additions (SPEC §9.2). */");
  for (const c of model.colors.filter((c) => c.group === "commerce")) {
    const note = c.override ? ` /* the kit: ${c.override.kitValue} */` : "";
    line(`  --${c.name}: ${colorValue(c)};${note}`);
  }
  line();
  line(
    "  /* The design widths of SPEC §9.2, for tests and the design-system pages. */",
  );
  for (const v of model.viewports) line(`  --viewport-${v.name}: ${v.value};`);
  line();
  line("  /* Layers, as z-(--z-…). */");
  for (const z of model.zIndex) line(`  --z-${z.name}: ${z.value};`);
  line();
  line("  /* Motion. */");
  for (const d of model.durations) line(`  --duration-${d.name}: ${d.value};`);
  line("}");
  line();
  line("@theme inline {");
  line("  /* Colour */");
  for (const c of model.colors) line(`  --color-${c.name}: var(--${c.name});`);
  line();
  line("  /* Radius: one --radius, and the scale derived from it (D27). */");
  for (const step of model.radius.steps)
    line(
      `  --radius-${step.step}: ${step.offset === 0 ? "var(--radius)" : `calc(var(--radius) ${step.offset < 0 ? "-" : "+"} ${Math.abs(step.offset)}px)`};`,
    );
  line();
  line("  /* Spacing: Tailwind's step. */");
  line(`  --spacing: ${rem(model.spacing.stepPx)};`);
  line();
  line(
    `  /* Type. ${model.font.variable} is set by next/font on <html> (apps/storefront/src/lib/fonts.ts, D28). */`,
  );
  line("  --font-sans:");
  for (const wrapped of wrapList(
    [`var(${model.font.variable}, ui-sans-serif)`, ...FONT_FALLBACK],
    4,
    80,
  ))
    line(wrapped);
  for (const w of model.weights) line(`  --font-weight-${w.name}: ${w.value};`);
  for (const t of model.text) {
    line(`  --text-${t.step}: ${rem(t.sizePx)};`);
    line(`  --text-${t.step}--line-height: ${rem(t.lineHeightPx)};`);
  }
  line();
  line("  /* Breakpoints: the kit's, which are Tailwind's. */");
  for (const b of model.breakpoints)
    line(`  --breakpoint-${b.name}: ${rem(b.px)};`);
  line();
  line("  /* Containers. */");
  for (const c of model.containers)
    line(`  --container-${c.name}: ${c.value};`);
  line();
  line("  /* Shadows: the kit's effect styles. */");
  for (const s of model.shadows)
    line(`  --shadow-${s.name}: ${shadowValue(s.layers)};`);
  line();
  line("  /* Easing. */");
  for (const e of model.easings) line(`  --ease-${e.name}: ${e.value};`);
  line("}");
  return `${out.join("\n")}\n`;
}

/**
 * A comma-separated list wrapped the way Prettier fills it: as many items per line as fit in
 * `width` columns after `indent` spaces; the last line ends with ";".
 */
export function wrapList(
  items: readonly string[],
  indent: number,
  width: number,
): string[] {
  const lines: string[] = [];
  let current = "";
  items.forEach((item, index) => {
    const piece = index === items.length - 1 ? `${item};` : `${item},`;
    // Prettier's fill wants room for the comma and the space after an item that isn't the last,
    // and doesn't count the closing ";".
    const last = index === items.length - 1;
    const needs = last ? item.length : item.length + 2;
    if (current !== "" && indent + current.length + 1 + needs > width) {
      lines.push(" ".repeat(indent) + current);
      current = piece;
    } else current = current === "" ? piece : `${current} ${piece}`;
  });
  lines.push(" ".repeat(indent) + current);
  return lines;
}

